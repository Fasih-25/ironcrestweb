// After `next build` with output: export → writes out/.htaccess for Hostinger (Apache/LiteSpeed):
// CSP with sha256 hashes of every inline script, security headers, caching and compression.
// Node 22.18+/24 strips the TypeScript types of lib/csp.ts natively.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { SECURITY_HEADERS, buildCsp, origin } from '../lib/csp.ts';

// In export mode Next writes to distDir when it is customised, else to out/.
const OUT = path.resolve(process.argv[2] ?? process.env.NEXT_DIST_DIR ?? 'out');

const htmlFiles = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    return statSync(p).isDirectory() ? htmlFiles(p) : p.endsWith('.html') ? [p] : [];
  });

const sha = (s) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`;
const hashes = new Set();
for (const file of htmlFiles(OUT)) {
  const html = readFileSync(file, 'utf8');
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
    const attrs = m[1] ?? '';
    if (/type=["']?application\/ld\+json/.test(attrs)) continue; // data block, not script
    const body = m[2] ?? '';
    hashes.add(sha(body));
    // next/script beforeInteractive ships its code inside self.__next_s.push([...,{children:"…"}])
    // and the client re-inserts it as a new inline script, which needs its own hash.
    if (body.includes('__next_s')) {
      for (const c of body.matchAll(/"children":("(?:[^"\\]|\\.)*")/g)) hashes.add(sha(JSON.parse(c[1])));
    }
  }
}

const csp = buildCsp({
  scriptSources: [...hashes],
  strictDynamic: false,
  scriptHosts: [origin(process.env.NEXT_PUBLIC_ANALYTICS_SRC)].filter(Boolean),
  connect: [origin(process.env.NEXT_PUBLIC_DEMO_ENDPOINT), origin(process.env.NEXT_PUBLIC_ANALYTICS_SRC)].filter(Boolean),
});

const q = (v) => `"${v.replace(/"/g, '\\"')}"`;
const htaccess = `# Generated by scripts/postexport.mjs. Do not edit; rebuild instead.
Options -Indexes
ErrorDocument 404 /404.html

<IfModule mod_headers.c>
  Header always set Content-Security-Policy ${q(csp)}
${SECURITY_HEADERS.map((h) => `  Header always set ${h.key} ${q(h.value)}`).join('\n')}
  <FilesMatch "\\.(js|css|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(webp|png|svg|ico)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
  <FilesMatch "\\.(html|txt|xml)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !=https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript image/svg+xml application/json text/plain application/xml
</IfModule>
`;

writeFileSync(path.join(OUT, '.htaccess'), htaccess);
console.log(`[postexport] wrote ${path.join(OUT, '.htaccess')} with ${hashes.size} script hashes`);
